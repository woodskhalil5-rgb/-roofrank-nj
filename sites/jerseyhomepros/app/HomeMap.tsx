"use client";

import { useEffect, useState } from "react";
import type { TradeSlug } from "../lib/trades";

/**
 * The clickable house: a photo with a heads-up-display layer on top. A scan
 * line sweeps once, then gold brackets lock onto each part of the home, each
 * linking to that trade's request form. The tags NAME areas; they never claim
 * to have detected a problem, because the page has no way to know.
 *
 * Two scenes. Outside, the front door is a "Go inside" control: the view
 * pushes in through the door and the inside photo (living room + kitchen)
 * takes over with its own brackets. "Back outside" reverses it. A true 3D
 * walkthrough needs a scanned house; this zoom-through gives the feeling
 * and stays fast on phones.
 *
 * Both photos are AI-generated by Khalil (no real address, no real people).
 * Bracket coordinates are in the 2048x1360 frame of each crop. The zones are
 * SVG <a> links, so they work with a keyboard; the trade cards below the
 * scan stay as the plain way in.
 */
type Zone = {
  slug: TradeSlug;
  label: string;
  hint: string;
  x: number; y: number; w: number; h: number;
  tag: "above" | "below" | "inside-bottom";
  /** Optional left edge for the tag, when the default would sit on a neighbour. */
  tagX?: number;
};

type Scene = "outside" | "inside";

const OUTSIDE: Zone[] = [
  { slug: "roofing", label: "Roofing", hint: "Leaks, storm damage, replacement", x: 551, y: 316, w: 901, h: 196, tag: "above" },
  { slug: "windows", label: "Windows & Doors", hint: "Window and door repair or replacement", x: 337, y: 501, w: 185, h: 490, tag: "above", tagX: 40 },
  { slug: "hvac", label: "Heating & Cooling", hint: "No heat, no AC, tune-ups", x: 629, y: 1001, w: 134, h: 122, tag: "above" },
  { slug: "pest", label: "Pest Control", hint: "Mice, insects, termites", x: 80, y: 1022, w: 520, h: 84, tag: "below" },
  { slug: "moving", label: "Moving", hint: "Local moves, packing, heavy items", x: 1444, y: 872, w: 324, h: 199, tag: "above" },
  { slug: "landscaping", label: "Landscaping", hint: "Lawn, planting, cleanups", x: 60, y: 1168, w: 1080, h: 172, tag: "inside-bottom" },
  { slug: "hardscaping", label: "Hardscaping", hint: "Patios, walkways, driveways", x: 1440, y: 1112, w: 580, h: 228, tag: "inside-bottom" },
];

const INSIDE: Zone[] = [
  { slug: "hvac", label: "Heating & Cooling", hint: "Vents, thermostat, no heat or AC", x: 800, y: 20, w: 330, h: 150, tag: "below" },
  { slug: "windows", label: "Windows & Doors", hint: "Drafty, broken or foggy windows", x: 870, y: 600, w: 760, h: 250, tag: "above" },
  { slug: "pest", label: "Pest Control", hint: "Ants, roaches, mice in the kitchen", x: 1775, y: 590, w: 200, h: 470, tag: "above", tagX: 1630 },
  { slug: "cleaning", label: "Cleaning", hint: "Deep cleans, kitchens, move-out", x: 1340, y: 900, w: 420, h: 330, tag: "below" },
  { slug: "moving", label: "Moving", hint: "Packing, local moves, heavy items", x: 60, y: 900, w: 300, h: 300, tag: "above" },
];

/** The front door in the outside photo, and the point the zoom pushes toward. */
const DOOR = { x: 915, y: 780, w: 125, h: 240 };
const DOOR_ORIGIN = `${((DOOR.x + DOOR.w / 2) / 2048) * 100}% ${((DOOR.y + DOOR.h / 2) / 1360) * 100}%`;

/** Tags are sized to stay readable on a laptop (about 16px on screen). */
const TAG_H = 62;
function tagWidth(label: string): number {
  return Math.round(label.length * 24 + 118);
}

function Bracket({ x, y, w, h }: { x: number; y: number; w: number; h: number }) {
  const c = Math.min(46, w / 3, h / 3);
  return (
    <path
      className="hudbracket"
      d={`M${x} ${y + c}V${y}H${x + c} M${x + w - c} ${y}H${x + w}V${y + c} M${x + w} ${y + h - c}V${y + h}H${x + w - c} M${x + c} ${y + h}H${x}V${y + h - c}`}
    />
  );
}

function ZoneLink({ z, i }: { z: Zone; i: number }) {
  const tw = tagWidth(z.label);
  const ty =
    z.tag === "above" ? z.y - TAG_H - 10
    : z.tag === "below" ? z.y + z.h + 10
    : z.y + z.h - TAG_H - 14;
  const tx = z.tagX ?? (z.tag === "inside-bottom" ? z.x + 14 : z.x);
  const n = String(i + 1).padStart(2, "0");
  return (
    <a href={`/${z.slug}#estimate`} className="hudzone"
       style={{ ["--d" as string]: `${0.9 + i * 0.16}s` }}
       aria-label={`${z.label}: ${z.hint}`}>
      <rect className="hudarea" x={z.x} y={z.y} width={z.w} height={z.h} />
      <Bracket x={z.x} y={z.y} w={z.w} h={z.h} />
      <circle className="hudpulse" cx={z.x + z.w / 2} cy={z.y + z.h / 2} r="16" />
      <circle className="huddot" cx={z.x + z.w / 2} cy={z.y + z.h / 2} r="10" />
      <g className="hudtag">
        <rect x={tx} y={ty} width={tw} height={TAG_H} rx="4" />
        <text x={tx + 18} y={ty + 42} className="hudnum">{n}</text>
        <text x={tx + 80} y={ty + 42} className="hudlabel">{z.label.toUpperCase()}</text>
      </g>
    </a>
  );
}

export default function HomeMap({ hero = false }: { hero?: boolean }) {
  const [scene, setScene] = useState<Scene>("outside");
  const [moving, setMoving] = useState(false);
  const [visited, setVisited] = useState(false);
  const zones = scene === "outside" ? OUTSIDE : INSIDE;

  // Fetch the inside photo once the page is idle, so the walk-in is instant.
  useEffect(() => {
    const t = setTimeout(() => { const i = new Image(); i.src = "/home-inside.webp"; }, 1500);
    return () => clearTimeout(t);
  }, []);

  function go(next: Scene) {
    const reduce = window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
    setVisited(true);
    if (reduce) { setScene(next); return; }
    setMoving(true);
    setTimeout(() => { setScene(next); setMoving(false); }, 650);
  }

  const cls = ["hud", `hud-${scene}`, moving ? "hudmoving" : "", visited ? "hudreturn" : ""].join(" ");

  return (
    <div className={hero ? "homemap homemaphero" : "homemap"} id="scan">
      {!hero && (
        <div className="homemaphead">
          <div className="eyebrow"><i></i> TAP THE PROBLEM</div>
          <p>Not sure who to call? Tap the part of the home that needs help.</p>
        </div>
      )}

      <div className={cls} style={{ ["--door" as string]: DOOR_ORIGIN }}>
        <picture key={scene} className="hudphoto">
          {scene === "outside" ? (
            <>
              <source srcSet="/home-hud.webp" type="image/webp" />
              <img src="/home-hud.jpg" width={1600} height={1062} loading={hero ? "eager" : "lazy"} decoding="async"
                   fetchPriority={hero ? "high" : "auto"}
                   alt="A modern two-story home with a lawn, shrubs, an AC unit, a garage and a driveway" />
            </>
          ) : (
            <>
              <source srcSet="/home-inside.webp" type="image/webp" />
              <img src="/home-inside.jpg" width={1600} height={1062} decoding="async"
                   alt="Inside the home: an entry hall with moving boxes, a living room with large windows, and a kitchen" />
            </>
          )}
        </picture>

        <svg key={`svg-${scene}`} viewBox="0 0 2048 1360" role="group"
             aria-label={scene === "outside" ? "Areas outside the home you can tap" : "Areas inside the home you can tap"}>
          <defs>
            <linearGradient id="hudScan" x1="0" y1="0" x2="0" y2="1">
              <stop offset="0" stopColor="#d6ad58" stopOpacity="0" />
              <stop offset=".85" stopColor="#d6ad58" stopOpacity=".28" />
              <stop offset="1" stopColor="#ffe6a8" stopOpacity=".9" />
            </linearGradient>
            <pattern id="hudGrid" width="64" height="64" patternUnits="userSpaceOnUse">
              <path d="M64 0H0V64" fill="none" stroke="#d6ad58" strokeOpacity=".09" strokeWidth="1.5" />
            </pattern>
          </defs>

          <rect className="hudgrid" width="2048" height="1360" fill="url(#hudGrid)" />
          <rect className="hudscan" x="0" y="-160" width="2048" height="160" fill="url(#hudScan)" />

          {/* status line: describes the interface, never a finding */}
          <g className="hudstatus">
            <rect x="28" y="28" width={scene === "outside" ? 800 : 740} height="66" rx="4" />
            <circle cx="66" cy="61" r="10" className="hudlive" />
            <text x="92" y="72">{scene === "outside" ? "OUTSIDE" : "INSIDE"} · {zones.length} AREAS · TAP ONE</text>
          </g>

          {zones.map((z, i) => <ZoneLink key={z.slug} z={z} i={i} />)}

          {scene === "outside" ? (
            <a href="#scan" className="hudzone huddoor" style={{ ["--d" as string]: "2.1s" }}
               aria-label="Go inside the house"
               onClick={(e) => { e.preventDefault(); go("inside"); }}>
              <rect className="hudarea" x={DOOR.x} y={DOOR.y} width={DOOR.w} height={DOOR.h} />
              <Bracket {...DOOR} />
              <g className="hudtag">
                <rect x={DOOR.x - 104} y={DOOR.y - TAG_H - 10} width="334" height={TAG_H} rx="4" />
                <text x={DOOR.x + DOOR.w / 2} y={DOOR.y - 30} textAnchor="middle" className="hudlabel">GO INSIDE →</text>
              </g>
            </a>
          ) : (
            <a href="#scan" className="hudzone huddoor" style={{ ["--d" as string]: "0.3s" }}
               aria-label="Back outside"
               onClick={(e) => { e.preventDefault(); go("outside"); }}>
              <g className="hudtag">
                <rect x="1700" y="28" width="320" height="66" rx="4" />
                <text x="1860" y="72" textAnchor="middle" className="hudlabel">← OUTSIDE</text>
              </g>
            </a>
          )}
        </svg>
      </div>

      {/* On a phone the tags are too small to read, so the names move into
          numbered buttons under the photo. */}
      <div className="homemaplegend">
        {zones.map((z, i) => (
          <a key={z.slug} href={`/${z.slug}#estimate`}><b>{String(i + 1).padStart(2, "0")}</b>{z.label}</a>
        ))}
        <button type="button" className="legenddoor" onClick={() => go(scene === "outside" ? "inside" : "outside")}>
          {scene === "outside" ? "Go inside the house →" : "← Back outside"}
        </button>
      </div>
    </div>
  );
}
